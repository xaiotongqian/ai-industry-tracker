const SITE_HREFS = new Set(["/models", "/funding", "/landscape", "/about"]);

export function isAllowedInsightHref(href: string): boolean {
  if (SITE_HREFS.has(href)) return true;
  const match = /^\/insights\/([a-z0-9-]+)$/.exec(href);
  return match != null && insights.some((item) => item.slug === match[1]);
}

export function getInsight(slug: string): Insight | undefined {
  return insights.find((item) => item.slug === slug);
}

export function pillarLabel(id: InsightPillar): string {
  return pillars.find((item) => item.id === id)?.label ?? id;
}

function articlePlain(insight: Insight): string {
  const raw = [insight.lede, ...insight.blocks.flatMap((block) => block.paragraphs)].join("\n");
  return raw.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
}

function assertLinks(slug: string, text: string, slugs: ReadonlySet<string>) {
  if (text.includes("](http")) {
    throw new Error(`External link in ${slug}`);
  }
  for (const match of text.matchAll(/\[([^\]]+)\]\((\/[^)\s]+)\)/g)) {
    const href = match[2] ?? "";
    const linked = /^\/insights\/([a-z0-9-]+)$/.exec(href);
    if (linked?.[1] === slug) throw new Error(`Self link in ${slug}`);
    if (!isAllowedInsightHref(href) || (linked && !slugs.has(linked[1]))) {
      throw new Error(`Bad link in ${slug}: ${href}`);
    }
  }
}

function assertCatalog(items: readonly Insight[]) {
  const slugs = new Set(items.map((item) => item.slug));
  if (slugs.size !== items.length) throw new Error("Duplicate insight slug");
  for (const item of items) {
    if (!/^[a-z0-9-]+$/.test(item.slug)) throw new Error(`Bad slug: ${item.slug}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(item.publishedOn)) throw new Error(`Bad date: ${item.slug}`);
    if (!item.topic.trim() || [...item.topic].length > 8) throw new Error(`Bad topic: ${item.slug}`);
    if (item.blocks.length < 2) throw new Error(`Need sections: ${item.slug}`);
    const ids = new Set<string>();
    let paragraphs = 0;
    for (const block of item.blocks) {
      if (!/^[a-z0-9-]+$/.test(block.id)) throw new Error(`Bad block id: ${item.slug}`);
      if (ids.has(block.id)) throw new Error(`Duplicate block id: ${item.slug}/${block.id}`);
      ids.add(block.id);
      if (!block.heading.trim()) throw new Error(`Missing heading: ${item.slug}`);
      paragraphs += block.paragraphs.length;
      for (const paragraph of block.paragraphs) {
        if (!paragraph.trim()) throw new Error(`Blank paragraph: ${item.slug}`);
        assertLinks(item.slug, paragraph, slugs);
      }
    }
    if (paragraphs < 8) throw new Error(`Thin essay ${item.slug}: ${paragraphs} paragraphs`);
    if (!articlePlain(item).includes(item.takeaway)) {
      throw new Error(`Takeaway is not in the body: ${item.slug}`);
    }
    if (item.related.length === 0) throw new Error(`No related links: ${item.slug}`);
    const hrefs = new Set<string>();
    for (const link of item.related) {
      if (hrefs.has(link.href)) throw new Error(`Duplicate related: ${item.slug}`);
      hrefs.add(link.href);
      if (!link.label.trim() || !link.note.trim()) throw new Error(`Related needs note: ${item.slug}`);
      if (!isAllowedInsightHref(link.href)) throw new Error(`Bad related: ${item.slug} ${link.href}`);
    }
    for (const gap of item.gaps ?? []) {
      if (!gap.label.trim() || !gap.reason.trim()) throw new Error(`Empty gap: ${item.slug}`);
    }
  }
}

